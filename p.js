exports.bulkUploadProducts = async () => {
  return await withConnection(async (connection) => {
    try {
      await connection.beginTransaction();

      // 🔹 1. Pehle saari categories ek baar fetch kar lo
      const [categories] = await connection.execute(
        `SELECT id, category_name FROM rajlaksmi_category`,
      );

      // 🔹 2. Category map bana lo (fast lookup ke liye)
      const categoryMap = {};
      categories.forEach((cat) => {
        categoryMap[cat.category_name] = cat.id;
      });

      // 🔹 3. Insert values prepare karo
      const values = [];

      for (const item of products) {
        const categoryId = categoryMap[item.category];

        if (!categoryId) {
          console.log(`Category not found: ${item.category}`);
          continue;
        }

        values.push([
          item.name,
          item.retailPrice,
          item.unit,
          item.purchasePrice,
          0, // is_featured
          item.status === "active" ? 1 : 0,
          0, // stock
          null, // images
          item.category,
          0, // best_saller
          categoryId,
        ]);
      }

      if (values.length === 0) {
        throw new Error("No valid products to insert");
      }

      // 🔹 4. Bulk Insert (single query - fast)
      const insertQuery = `
        INSERT INTO rajlaksmi_product
        (product_name, product_price, product_weight, product_purchase_price,
         is_featured, is_active, product_stock,
         product_images, category_name, best_saller, category_id)
        VALUES ?
      `;

      await connection.query(insertQuery, [values]);

      await connection.commit();

      return {
        success: true,
        inserted: values.length,
      };
    } catch (error) {
      throw error;
    }
  });
};
